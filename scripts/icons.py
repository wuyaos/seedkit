#!/usr/bin/env python3
"""Build web/static/vendor/lucide.svg: a subset sprite of the Lucide icon set.

Only the icons referenced from web/static/{index.html,app.js} (as
`vendor/lucide.svg#<name>`) are kept, so the embedded binary stays small.

Usage:  python scripts/icons.py            # uses pinned LUCIDE_VERSION
        python scripts/icons.py 0.552.0    # override version
"""
import re
import hashlib
import sys
import urllib.request
from pathlib import Path

LUCIDE_VERSION = "0.552.0"
ROOT = Path(__file__).resolve().parent.parent / "web" / "static"
OUT = ROOT / "vendor" / "lucide.svg"
SRC = [ROOT / "index.html", ROOT / "app.js"]


def main() -> int:
    ver = sys.argv[1] if len(sys.argv) > 1 else LUCIDE_VERSION
    used = set()
    for f in SRC:
        used.update(re.findall(r"vendor/lucide\.svg(?:\?v=[a-zA-Z0-9]+)?#([a-z0-9-]+)", f.read_text("utf-8")))
    if not used:
        print("no icon references found", file=sys.stderr)
        return 1

    url = f"https://unpkg.com/lucide-static@{ver}/sprite.svg"
    sprite = urllib.request.urlopen(url, timeout=60).read().decode("utf-8")
    symbols = {m[1]: m[0] for m in re.findall(r'(<symbol id="([a-z0-9-]+)".*?</symbol>)', sprite, re.S)}

    missing = sorted(used - symbols.keys())
    if missing:
        print("unknown lucide icons:", ", ".join(missing), file=sys.stderr)
        return 1

    attrs = ('viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
             'stroke-linecap="round" stroke-linejoin="round"')
    body = "\n".join(
        re.sub(r'^<symbol id="([a-z0-9-]+)"[^>]*>', rf'<symbol id="\1" {attrs}>',
               re.sub(r"\s+", " ", symbols[n]).replace("> <", "><"))
        for n in sorted(used)
    )
    payload = (
        f'<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- lucide-static v{ver} (ISC) — subset generated by scripts/icons.py, do not edit -->\n"
        f'<svg xmlns="http://www.w3.org/2000/svg"><defs>\n{body}\n</defs></svg>\n'
    ).encode("utf-8")
    OUT.write_bytes(payload)
    version = hashlib.sha256(payload).hexdigest()[:12]
    for f in SRC:
        text = f.read_text("utf-8")
        updated = re.sub(r"vendor/lucide\.svg(?:\?v=[a-zA-Z0-9]+)?#",
                         f"vendor/lucide.svg?v={version}#", text)
        if updated != text:
            f.write_bytes(updated.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT.parent.parent)}: {len(used)} icons from lucide v{ver}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
